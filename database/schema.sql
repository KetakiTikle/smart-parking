-- =====================================================================
-- Smart Parking Management System - Database schema and seed data
-- Requires MySQL 8.0.16 or newer (CHECK constraints, recursive CTE)
-- Run this whole file in MySQL Workbench (Ctrl+Shift+Enter).
-- WARNING: it drops and recreates the smart_parking database.
-- =====================================================================
DROP DATABASE IF EXISTS smart_parking;
CREATE DATABASE smart_parking CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE smart_parking;

-- ---------------------------------------------------------------------
-- MODULE 1: users
-- ---------------------------------------------------------------------
CREATE TABLE users (
    user_id        INT AUTO_INCREMENT PRIMARY KEY,
    name           VARCHAR(50)  NOT NULL,
    email          VARCHAR(100) NOT NULL,
    phone          CHAR(10)     NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,           -- BCrypt hash, never plain text
    role           ENUM('DRIVER','ADMIN') NOT NULL DEFAULT 'DRIVER',
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_phone CHECK (phone REGEXP '^[6-9][0-9]{9}$')
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- MODULE 2: parking lots, slots, reservations
-- ---------------------------------------------------------------------
CREATE TABLE parking_lots (
    lot_id          INT AUTO_INCREMENT PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    location        VARCHAR(100) NOT NULL,
    address         VARCHAR(200),
    total_slots     INT          NOT NULL,
    price_per_hour  DECIMAL(8,2) NOT NULL,
    CONSTRAINT chk_lot_slots CHECK (total_slots > 0),
    CONSTRAINT chk_lot_price CHECK (price_per_hour > 0)
) ENGINE=InnoDB;

CREATE TABLE slots (
    slot_id      INT AUTO_INCREMENT PRIMARY KEY,
    lot_id       INT         NOT NULL,
    slot_number  VARCHAR(10) NOT NULL,
    status       ENUM('ACTIVE','MAINTENANCE') NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT uq_slot_in_lot UNIQUE (lot_id, slot_number),
    CONSTRAINT fk_slots_lot FOREIGN KEY (lot_id)
        REFERENCES parking_lots (lot_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE reservations (
    reservation_id  INT AUTO_INCREMENT PRIMARY KEY,
    user_id         INT           NOT NULL,
    slot_id         INT           NOT NULL,
    vehicle_no      VARCHAR(10)   NOT NULL,
    start_time      DATETIME      NOT NULL,
    end_time        DATETIME      NOT NULL,
    total_amount    DECIMAL(10,2) NOT NULL,
    status          ENUM('CONFIRMED','CANCELLED','COMPLETED') NOT NULL DEFAULT 'CONFIRMED',
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at    DATETIME      NULL,
    CONSTRAINT chk_res_time CHECK (end_time > start_time),
    CONSTRAINT fk_res_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_res_slot FOREIGN KEY (slot_id) REFERENCES slots (slot_id),
    INDEX idx_res_slot_time (slot_id, status, start_time, end_time),
    INDEX idx_res_user (user_id)
) ENGINE=InnoDB;
-- NOTE: reservations are never hard-deleted. Cancelling only sets
-- status = 'CANCELLED' (NFR-2: prevent accidental booking deletion).

