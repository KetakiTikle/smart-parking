-- Quick check
SELECT l.name, COUNT(s.slot_id) AS slots,
       SUM(s.status = 'ACTIVE') AS active_slots
FROM parking_lots l JOIN slots s ON s.lot_id = l.lot_id
GROUP BY l.lot_id, l.name;
