-- Create slots S01..Snn for every lot (recursive number generator)
INSERT INTO slots (lot_id, slot_number)
SELECT l.lot_id, CONCAT('S', LPAD(n.n, 2, '0'))
FROM parking_lots l
JOIN (WITH RECURSIVE seq (n) AS (
          SELECT 1 UNION ALL SELECT n + 1 FROM seq WHERE n < 20
      )
      SELECT n FROM seq) n
  ON n.n <= l.total_slots;

